"""Write docs/test-matrix.md: which tests exercise each route.

    PYTHONPATH=backend/scripts pytest -p route_matrix -m "schema or not schema" -q


It wraps the Flask test client, records every request the suite makes (route,
method, status, test), and writes one row per route and method with a passing
happy-path test (2xx) and a failure-path test (4xx). A route with a missing
side is listed as a gap. Rewrites the file only when the whole suite passed.
"""

import subprocess
from collections import defaultdict
from pathlib import Path

import pytest
from flask.testing import FlaskClient
from werkzeug.exceptions import HTTPException

FAILURE_CODES = {400, 401, 403, 404, 409, 423, 429}
OUT = Path(__file__).resolve().parents[2] / "docs" / "test-matrix.md"

seen = defaultdict(lambda: {"ok": set(), "fail": set()})
all_routes = {}
current = {"test": None, "passed": {}}
_original = FlaskClient.open


def _open(self, *args, **kwargs):
    response = _original(self, *args, **kwargs)
    req = response.request if hasattr(response, "request") else None
    if req is not None and current["test"]:
        adapter = self.application.url_map.bind("localhost")
        try:
            rule, _ = adapter.match(req.path, method=req.method, return_rule=True)
        except HTTPException:
            return response
        key = (rule.rule, req.method)
        if response.status_code < 300:
            seen[key]["ok"].add(current["test"])
        elif response.status_code in FAILURE_CODES:
            seen[key]["fail"].add(current["test"])
    return response


FlaskClient.open = _open


def pytest_runtest_setup(item):
    current["test"] = item.nodeid


def pytest_runtest_logreport(report):
    if report.when == "call":
        current["passed"][report.nodeid] = report.passed


@pytest.fixture(autouse=True)
def _collect_routes(app):
    for rule in app.url_map.iter_rules():
        for method in rule.methods - {"HEAD", "OPTIONS"}:
            if rule.rule.startswith("/api"):
                all_routes[(rule.rule, method)] = True


def pytest_sessionfinish(session, exitstatus):
    if exitstatus != 0:
        return
    passed = current["passed"]
    rows, gaps = [], []
    for key in sorted(all_routes):
        ok = sorted(t for t in seen[key]["ok"] if passed.get(t))
        fail = sorted(t for t in seen[key]["fail"] if passed.get(t))
        path, method = key
        rows.append(f"| {method} | `{path}` | {_cell(ok)} | {_cell(fail)} |")
        if not ok or not fail:
            missing = "happy-path" if not ok else "failure-path"
            gaps.append(f"- {method} `{path}`: no {missing} test")
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    text = [
        "# Test matrix: every route against its tests",
        "",
        f"Generated by `backend/scripts/route_matrix.py` against commit `{commit}` "
        f"({len(rows)} route and method pairs). Do not edit by hand. A test fails "
        "when a route in the code has no row here.",
        "",
        "Happy path = a passing test that got a 2xx from the route. Failure path = "
        "a passing test that got 400, 401, 403, 404, 409, 423 or 429. Each cell "
        "shows the count and one example test.",
        "",
        "## Gaps",
        "",
        *(gaps or ["None: every route has a happy-path and a failure-path test."]),
        "",
        "## Routes",
        "",
        "| Method | Route | Happy path | Failure path |",
        "|--------|-------|------------|--------------|",
        *rows,
        "",
    ]
    OUT.write_text("\n".join(text))


def _cell(tests):
    if not tests:
        return "**none**"
    return f"{len(tests)}: `{tests[0].split('/')[-1]}`"
